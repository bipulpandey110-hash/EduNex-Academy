from django.contrib import admin
from .models import Student, Teacher, Course, Batch, Attendance, FeePayment, Assignment, ExamResult, Enquiry, Notice
@admin.register(Student)
class StudentAdmin(admin.ModelAdmin): list_display=('student_id','full_name','current_class','program','status','joined_on'); search_fields=('student_id','full_name','phone','email'); list_filter=('status','current_class','program')
@admin.register(Teacher)
class TeacherAdmin(admin.ModelAdmin): list_display=('teacher_id','full_name','subject','active'); search_fields=('teacher_id','full_name','email'); list_filter=('subject','active')
@admin.register(Course)
class CourseAdmin(admin.ModelAdmin): list_display=('title','category','target_level','fee','active'); search_fields=('title','category'); list_filter=('active','category')
@admin.register(Batch)
class BatchAdmin(admin.ModelAdmin): list_display=('name','course','teacher','start_time','room','active'); list_filter=('course','active')
@admin.register(Attendance)
class AttendanceAdmin(admin.ModelAdmin): list_display=('student','batch','date','status'); list_filter=('date','status','batch'); search_fields=('student__full_name','student__student_id')
@admin.register(FeePayment)
class FeePaymentAdmin(admin.ModelAdmin): list_display=('student','amount','due_date','paid_on','status'); list_filter=('status','due_date'); search_fields=('student__full_name','reference')
@admin.register(Assignment)
class AssignmentAdmin(admin.ModelAdmin): list_display=('title','batch','due_date','created_at'); search_fields=('title','batch__name')
@admin.register(ExamResult)
class ExamResultAdmin(admin.ModelAdmin): list_display=('student','course','exam_name','score','max_score','exam_date'); search_fields=('student__full_name','exam_name')
@admin.register(Enquiry)
class EnquiryAdmin(admin.ModelAdmin): list_display=('full_name','phone','program','status','created_at'); list_filter=('status','program'); search_fields=('full_name','phone','email')
@admin.register(Notice)
class NoticeAdmin(admin.ModelAdmin): list_display=('title','audience','published','created_at'); list_filter=('audience','published')
